#!/usr/bin/env python3
"""Generate a deterministic *illustrative* snapshot for documentation.

This is NOT captured telemetry. It produces a synthetic snapshot with the same
schema and PromQL-derived shapes as ``collect-demo-metrics.py`` so the README can
show what the dashboard looks like before anyone provisions a cluster.

Every generated snapshot is stamped ``"synthetic": true`` and the renderer
watermarks the resulting SVGs accordingly.

To capture real data instead:
    ./scripts/demo-gke.sh up
    ./scripts/demo-gke.sh snapshot

Usage:
    python3 scripts/generate-example-snapshot.py --output demo/snapshots/example.json
"""

from __future__ import annotations

import argparse
import json
import math
import random
from datetime import datetime, timedelta, timezone

# Fixed seed keeps the committed example stable across regenerations.
SEED = 20261027
POINTS = 120
STEP_SECONDS = 30


def wave(i: int, n: int, base: float, amp: float, phase: float = 0.0) -> float:
    """Smooth periodic signal with a little deterministic noise."""
    rng = random.Random(SEED + i)
    t = i / max(n - 1, 1)
    signal = base + amp * math.sin(2 * math.pi * (t * 2.0 + phase))
    signal += amp * 0.25 * math.sin(2 * math.pi * (t * 7.0 + phase))
    return max(0.0, signal + rng.uniform(-amp * 0.06, amp * 0.06))


def build_series(
    labels: list[str],
    base: float,
    amp: float,
    start_ts: float,
    phase_step: float = 0.12,
) -> list[dict]:
    out = []
    for idx, label in enumerate(labels):
        points = []
        for i in range(POINTS):
            ts = start_ts + i * STEP_SECONDS
            points.append(
                {"t": ts, "v": round(wave(i + idx * 17, POINTS, base, amp, idx * phase_step), 3)}
            )
        out.append({"label": label, "points": points})
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="demo/snapshots/example.json")
    parser.add_argument("--cluster", default="gpu-telemetry-demo")
    args = parser.parse_args()

    now = datetime.now(timezone.utc).replace(microsecond=0)
    start_ts = (now - timedelta(seconds=POINTS * STEP_SECONDS)).timestamp()

    gpus = ["GPU-0", "GPU-1"]

    snapshot = {
        "generated_at": now.isoformat(),
        "cluster": args.cluster,
        "source": "synthetic",
        "synthetic": True,
        "note": (
            "Illustrative data generated by scripts/generate-example-snapshot.py. "
            "Not captured from a live cluster. Run ./scripts/demo-gke.sh snapshot "
            "to replace it with real telemetry."
        ),
        "summary": {
            "avg_sm_utilization": {
                "title": "Average SM Utilization",
                "unit": "%",
                "value": 78.4,
            },
            "vram_utilization": {
                "title": "VRAM Utilization",
                "unit": "%",
                "value": 71.2,
            },
            "max_temperature": {
                "title": "Max GPU Temperature",
                "unit": "°C",
                "value": 72.0,
            },
            "xid_errors_1h": {
                "title": "GPU XID Errors (1h)",
                "unit": "count",
                "value": 0.0,
            },
        },
        "series": {
            "sm_utilization": {
                "title": "SM Utilization per GPU",
                "unit": "%",
                "series": build_series(gpus, 74.0, 18.0, start_ts),
            },
            "vram_used": {
                "title": "VRAM Used per GPU",
                "unit": "MiB",
                "series": build_series(gpus, 15200.0, 900.0, start_ts, 0.05),
            },
            "gpu_temperature": {
                "title": "GPU Temperature per GPU",
                "unit": "°C",
                "series": build_series(gpus, 68.0, 6.0, start_ts, 0.08),
            },
            "pcie_tx": {
                "title": "PCIe TX Throughput per GPU",
                "unit": "MB/s",
                "series": build_series(gpus, 3100.0, 700.0, start_ts, 0.2),
            },
            "pcie_rx": {
                "title": "PCIe RX Throughput per GPU",
                "unit": "MB/s",
                "series": build_series(gpus, 2900.0, 650.0, start_ts, 0.25),
            },
            "tcp_rtt_p99": {
                "title": "TCP Round-Trip Latency p99 (eBPF)",
                "unit": "µs",
                "series": build_series(["p99 RTT"], 420.0, 160.0, start_ts),
            },
            "tcp_rtt_p50": {
                "title": "TCP Round-Trip Latency p50 (eBPF)",
                "unit": "µs",
                "series": build_series(["p50 RTT"], 120.0, 45.0, start_ts, 0.3),
            },
        },
        "errors": [],
    }

    with open(args.output, "w") as f:
        json.dump(snapshot, f, indent=2)
        f.write("\n")

    print(f"wrote {args.output} (synthetic, {POINTS} points/series)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
